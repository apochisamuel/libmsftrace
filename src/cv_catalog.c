static const char *mt_lookup_catalog(const mt_catalog16 *items, size_t count, uint16_t value) {
    size_t low = 0u;
    size_t high = count;
    while (low < high) {
        size_t mid = low + (high - low) / 2u;
        if (items[mid].value < value) low = mid + 1u;
        else high = mid;
    }
    return low < count && items[low].value == value ? items[low].name : "UNKNOWN";
}

const char *mt_cv_leaf_name(uint16_t leaf) {
    return mt_lookup_catalog(mt_leaf_catalog,
                             sizeof(mt_leaf_catalog) / sizeof(mt_leaf_catalog[0]), leaf);
}

const char *mt_cv_symbol_name(uint16_t kind) {
    return mt_lookup_catalog(mt_symbol_catalog,
                             sizeof(mt_symbol_catalog) / sizeof(mt_symbol_catalog[0]), kind);
}

const char *mt_cv_machine_name(uint16_t machine) {
    return mt_lookup_catalog(mt_machine_catalog,
                             sizeof(mt_machine_catalog) / sizeof(mt_machine_catalog[0]), machine);
}

const char *mt_cv_register_name(uint16_t machine, uint16_t reg) {
    size_t low = 0u;
    size_t high = sizeof(mt_register_catalog_items) / sizeof(mt_register_catalog_items[0]);
    while (low < high) {
        size_t mid = low + (high - low) / 2u;
        if (mt_register_catalog_items[mid].machine < machine ||
            (mt_register_catalog_items[mid].machine == machine && mt_register_catalog_items[mid].reg < reg)) {
            low = mid + 1u;
        } else {
            high = mid;
        }
    }
    size_t count = sizeof(mt_register_catalog_items) / sizeof(mt_register_catalog_items[0]);
    if (low < count && mt_register_catalog_items[low].machine == machine &&
        mt_register_catalog_items[low].reg == reg) return mt_register_catalog_items[low].name;
    return "UNKNOWN";
}
